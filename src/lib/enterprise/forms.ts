export function formByKey(key: string): FormTemplate | undefined {
  return CONSENT_FORMS.find((f) => f.key === key);
}

export function renderFormBody(tpl: FormTemplate, opts: { employee: string; company: string; date?: string }): string {
  return tpl.body
    .replace(/\{\{employee\}\}/g, opts.employee)
    .replace(/\{\{company\}\}/g, opts.company)
    .replace(/\{\{date\}\}/g, opts.date || new Date().toLocaleDateString());
}
